function matchKeywords(answer, keywordGroups){
    for(const group of keywordGroups){
        let allMatch = true;
        for(const kw of group){
            if(!answer.includes(kw.toLowerCase())){ allMatch=false; break; }
        }
        if(allMatch) return true;
    }
    return false;
}

function gradeAnswer(qnum, answer, answer2=''){
    const qs = getQuestions();
    if(!qs[qnum]) return 0;
    const q = qs[qnum];
    const ans = (answer||'').toLowerCase().trim();
    if(q.type==='former_latter'){
        const a1 = (answer||'').toLowerCase().trim();
        const a2 = (answer2||'').toLowerCase().trim();
        const f = matchKeywords(a1, q.keywords_former);
        const l = matchKeywords(a2, q.keywords_latter);
        return (f && l) ? 1 : 0;
    }
    return matchKeywords(ans, q.keywords) ? 1 : 0;
}

